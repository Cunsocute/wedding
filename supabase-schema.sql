-- Chạy trong Supabase SQL Editor.
create table if not exists public.wedding_wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  message text not null check (char_length(message) between 2 and 500),
  created_at timestamptz not null default now()
);

create table if not exists public.wedding_rsvps (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 80),
  attendance text not null,
  guests integer not null default 1 check (guests between 1 and 5),
  side text not null,
  message text check (char_length(coalesce(message, '')) <= 350),
  created_at timestamptz not null default now()
);

alter table public.wedding_wishes enable row level security;
alter table public.wedding_rsvps enable row level security;

drop policy if exists "Anyone can read wedding wishes" on public.wedding_wishes;
create policy "Anyone can read wedding wishes" on public.wedding_wishes
  for select to anon, authenticated using (true);

drop policy if exists "Anyone can send wedding wishes" on public.wedding_wishes;
create policy "Anyone can send wedding wishes" on public.wedding_wishes
  for insert to anon, authenticated with check (true);

drop policy if exists "Anyone can submit RSVP" on public.wedding_rsvps;
create policy "Anyone can submit RSVP" on public.wedding_rsvps
  for insert to anon, authenticated with check (true);

